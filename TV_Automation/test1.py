# ============================================================
# LOCK DEVICE
# ============================================================

def lock_device(
    token: str,
    device_id: str,
    *,
    automation: bool = False,
    api_server: str = HS_API_SERVER
) -> requests.Response:

    api_url = f"{api_server}/v0/devices/lock"

    headers = {
        "Authorization": f"Bearer {token}"
    }

    data = {
        "device_id": device_id
    }

    params = {}

    if automation:
        params["automation"] = True

    response = requests.post(
        api_url,
        headers=headers,
        json=data,
        params=params
    )

    return response


# ============================================================
# INSTALL APPLICATION
# ============================================================

def install_app(
    token: str,
    app_id: str,
    device_id: str,
    *,
    api_server: str = HS_API_SERVER
) -> requests.Response:

    api_url = (
        f"{api_server}/v1/app/"
        f"{app_id}/install/"
        f"{device_id}"
    )

    headers = {
        "Authorization": f"Bearer {token}"
    }

    print()
    print("----------------------------------------")
    print("INSTALLING APPLICATION")
    print("----------------------------------------")

    print(f"APP ID: {app_id}")
    print(f"Device ID: {device_id}")
    print(f"Install URL: {api_url}")

    response = requests.post(
        api_url,
        headers=headers
    )

    print()
    print(
        f"Install response status: "
        f"{response.status_code}"
    )

    print("Install response:")
    print(response.text)

    # Save response for Jenkins
    try:

        with open(
            "headspin_install_response.json",
            "w"
        ) as f:

            f.write(response.text)

        print()
        print(
            "Install response saved to "
            "headspin_install_response.json"
        )

    except Exception as e:

        print(
            f"Warning: Could not save install response: {e}"
        )

    return response


# ============================================================
# START CAPTURE SESSION
# ============================================================

def start_capture_session(
    token: str,
    device_id: str,
    *,
    api_server: str = HS_API_SERVER,
    **kwargs
) -> requests.Response:

    api_url = f"{api_server}/v0/sessions"

    headers = {
        "Authorization": f"Bearer {token}"
    }

    data = {
        "session_type": "capture",
        "allow_replace": True,
        "device_id": device_id
    }

    # Prevent network capture parameters
    kwargs.pop("network_capture", None)
    kwargs.pop("capture_network", None)

    data.update(kwargs)

    response = requests.post(
        api_url,
        headers=headers,
        json=data
    )

    return response


# ============================================================
# STOP CAPTURE SESSION
# ============================================================

def stop_capture_session(
    token: str,
    session_id: str,
    *,
    api_server: str = HS_API_SERVER
) -> requests.Response:

    api_url = f"{api_server}/v0/sessions/{session_id}"

    headers = {
        "Authorization": f"Bearer {token}"
    }

    data = {
        "active": False
    }

    response = requests.patch(
        api_url,
        headers=headers,
        json=data
    )

    return response


